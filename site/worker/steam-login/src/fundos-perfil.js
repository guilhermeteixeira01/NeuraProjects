export const FUNDOS_PERFIL = [...MAPAS_FUNDO, ...FUNDOS_EVENTO.map(f => f.id)]
export const eventoDoFundo = id => FUNDOS_EVENTO.find(f => f.id === id) || null
const nomeMapa = id => id === 'dust2' ? 'Dust II' : id.charAt(0).toUpperCase() + id.slice(1)
export const nomeFundoPerfil = id => {
 const evento = eventoDoFundo(id)
 return evento ? `${nomeMapa(evento.mapa)} · ${evento.evento}` : nomeMapa(MAPAS_FUNDO.includes(id) ? id : 'mirage')
}
export const imagemFundoPerfil = id => {
 const evento = eventoDoFundo(id)
 return evento ? `/assets/mapas/${encodeURIComponent(evento.arquivo)}` : `/neurapick/maps/${MAPAS_FUNDO.includes(id) ? id : 'mirage'}.jpg`
}
export const podeUsarFundoPerfil = (id, perfil) => {
 if (id == null) return true
 if (!FUNDOS_PERFIL.includes(id)) return false
 const evento = eventoDoFundo(id)
 return !evento || !!perfil?.insignias?.[evento.insignia]
}
